import { execFile } from "node:child_process"
import { access, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { promisify } from "node:util"

export const OSBE_CHROME_STORE_PUBLISHER_ID =
  "cb34bb3b-8b83-4527-99df-ec17a12d952c"

const DATA_USAGE_LABELS = {
  authenticationInformation: "Authentication information",
  financialAndPaymentInformation: "Financial and payment information",
  healthInformation: "Health information",
  location: "Location",
  personalCommunications: "Personal communications",
  personallyIdentifiableInformation: "Personally identifiable information",
  userActivity: "User activity",
  webHistory: "Web history",
  websiteContent: "Website content"
}
const execFileAsync = promisify(execFile)

export function chromeStoreDashboardUrl(extension) {
  if (!extension.store.storeId) {
    return `https://chrome.google.com/webstore/devconsole/${OSBE_CHROME_STORE_PUBLISHER_ID}`
  }

  return `https://chrome.google.com/webstore/devconsole/${OSBE_CHROME_STORE_PUBLISHER_ID}/${extension.store.storeId}/edit`
}

export function chromeStoreListingUrl(storeId) {
  return `https://chromewebstore.google.com/detail/${storeId}`
}

export function expectedPrivacyPolicyUrl(slug) {
  return `https://github.com/FranciscoMoretti/osbe/blob/main/extensions/${slug}/PRIVACY.md`
}

export function renderStoreSubmission(extension) {
  const permissionSections = [
    ...extension.permissions.map((permission) =>
      renderPermission(permission.name, permission.justification)
    ),
    ...extension.hostPermissions.map((permission) =>
      renderPermission(permission.name, permission.justification)
    )
  ].join("\n\n")
  const dataUsage =
    extension.dataUsage.length === 0
      ? "Select no user-data categories."
      : `Select:\n\n${textBlock(
          extension.dataUsage.map(dataUsageLabel).join("\n")
        )}`
  const screenshotList = extension.store.screenshots
    .map((screenshot) => `- \`${screenshot.file}\``)
    .join("\n")
  const promoTileList =
    extension.store.promoTiles.length === 0
      ? "No promotional tiles are required."
      : extension.store.promoTiles
          .map((promoTile) => `- \`${promoTile.file}\` (${promoTile.kind})`)
          .join("\n")
  const reviewLogin = extension.store.review.loginRequired
    ? "Login or credentials are required; describe them in the dashboard without committing secrets."
    : "No account, login, or credentials are required."
  const submissionMode = extension.store.storeId
    ? `Existing item: \`${extension.store.storeId}\`\n\n- Public listing: ${chromeStoreListingUrl(
        extension.store.storeId
      )}\n- Developer dashboard: ${chromeStoreDashboardUrl(extension)}`
    : `First submission: create the item manually in the developer dashboard, upload the package, then persist the assigned ID with:\n\n\`\`\`bash\npnpm extension store-id ${extension.slug} <32-character-store-id>\n\`\`\``

  return `# Chrome Web Store Submission

Generated from \`extension.config.json\`. Do not edit this file directly.
Regenerate it with \`pnpm extension store-dossier ${extension.slug}\`.

## Submission Mode

${submissionMode}

## Store Listing

### Title From Package

${textBlock(extension.displayName)}

### Summary From Package

${textBlock(extension.summary)}

### Description

${textBlock(extension.store.description)}

### Category

${textBlock(extension.store.category)}

### Language

${textBlock(extension.store.language)}

### Store Icon

\`store-assets/store-icon-128.png\`

### Screenshots

${screenshotList}

### Promotional Tiles

${promoTileList}

### Homepage URL

${textBlock(extension.store.homepageUrl)}

### Support URL

${textBlock(extension.store.supportUrl)}

### Mature Content

${textBlock(extension.store.matureContent ? "Yes" : "No")}

## Privacy Practices

### Single Purpose

${textBlock(extension.singlePurpose)}

### Permission Justifications

${permissionSections || "No permissions or host permissions are requested."}

### Remote Code

Select \`No\` and use:

${textBlock(extension.remoteCode.justification)}

### Data Types

${dataUsage}

### Data Usage Certifications

Confirm all three Chrome Web Store Limited Use disclosures:

- User data is not sold or transferred outside approved use cases.
- User data is not used or transferred for unrelated purposes.
- User data is not used or transferred for creditworthiness or lending.

### Privacy Policy URL

${textBlock(extension.store.privacyPolicyUrl)}

## Test Instructions

### Login Or Credentials

${textBlock(reviewLogin)}

### Instructions

${textBlock(extension.store.review.instructions)}

## Distribution

### Visibility

${textBlock(titleCase(extension.store.visibility))}

### Pricing

${textBlock(
  extension.store.pricing === "free" ? "Free" : "Contains in-app purchases"
)}

### Regions

${textBlock("All regions")}

### Publishing

${textBlock(
  extension.store.automaticPublish
    ? "Publish automatically after the item passes review"
    : "Stage the approved item for manual publication"
)}

## Package

\`extensions/${extension.slug}/build/chrome-mv3-prod.zip\`
`
}

export async function writeStoreSubmission(repoRoot, extension) {
  const destination = path.join(
    repoRoot,
    "extensions",
    extension.slug,
    "store-assets",
    "chrome-web-store-listing.md"
  )
  await writeFile(destination, renderStoreSubmission(extension))
  return destination
}

export async function persistStoreId(repoRoot, extension, storeId) {
  if (!/^[a-p]{32}$/.test(storeId)) {
    throw new Error(
      "Chrome Web Store IDs must contain exactly 32 characters from a-p."
    )
  }

  const configPath = path.join(
    repoRoot,
    "extensions",
    extension.slug,
    "extension.config.json"
  )
  const config = JSON.parse(await readFile(configPath, "utf8"))
  if (config.store.storeId && config.store.storeId !== storeId) {
    throw new Error(
      `${extension.slug} already has Chrome Web Store ID ${config.store.storeId}; refusing to replace it with ${storeId}.`
    )
  }
  config.store.storeId = storeId
  await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`)
  await writeStoreSubmission(repoRoot, config)
}

export async function createStorePreflightReport(
  repoRoot,
  extension,
  {
    fetchImpl = globalThis.fetch,
    online = true,
    readPackagedManifest = readZipManifest,
    validationErrors = []
  } = {}
) {
  const packageJson = JSON.parse(
    await readFile(
      path.join(repoRoot, "extensions", extension.slug, "package.json"),
      "utf8"
    )
  )
  const zipPath = path.join(
    repoRoot,
    "extensions",
    extension.slug,
    "build",
    "chrome-mv3-prod.zip"
  )
  const checks = []
  const errors = [...validationErrors]

  checks.push(
    validationErrors.length === 0
      ? "✓ Metadata, manifest permissions, assets, and generated dossier are aligned."
      : `✗ Extension validation found ${validationErrors.length} problem(s).`
  )

  if (await exists(zipPath)) {
    try {
      const manifest = await readPackagedManifest(zipPath)
      const packageProblems = []
      const expectedPermissions = extension.permissions.map(
        (permission) => permission.name
      )
      const expectedHostPermissions = extension.hostPermissions.map(
        (permission) => permission.name
      )

      if (manifest.version !== packageJson.version) {
        packageProblems.push(
          `packaged version ${
            manifest.version ?? "(missing)"
          } does not match package.json ${packageJson.version}`
        )
      }
      if (!sameValues(manifest.permissions ?? [], expectedPermissions)) {
        packageProblems.push(
          "packaged manifest permissions do not match extension.config.json"
        )
      }
      if (
        !sameValues(manifest.host_permissions ?? [], expectedHostPermissions)
      ) {
        packageProblems.push(
          "packaged manifest host permissions do not match extension.config.json"
        )
      }

      if (packageProblems.length === 0) {
        checks.push(
          `✓ Package manifest matches version ${packageJson.version} and declared permissions: ${zipPath}`
        )
      } else {
        errors.push(
          ...packageProblems.map((problem) => `${extension.slug}: ${problem}`)
        )
        checks.push(
          `✗ Package manifest has ${packageProblems.length} readiness problem(s).`
        )
      }
    } catch (error) {
      errors.push(
        `${extension.slug}: could not inspect packaged ZIP: ${
          error instanceof Error ? error.message : error
        }`
      )
      checks.push("✗ Packaged ZIP could not be inspected.")
    }
  } else {
    errors.push(
      `${extension.slug}: missing packaged ZIP; run pnpm extension package ${extension.slug}`
    )
    checks.push(`✗ Package is missing for version ${packageJson.version}.`)
  }

  if (extension.store.storeId) {
    checks.push(`✓ Chrome Web Store ID: ${extension.store.storeId}`)
  } else {
    checks.push(
      "• First submission: the Chrome Web Store will assign the item ID after manual creation."
    )
  }

  const privacyPolicyError = getPrivacyPolicyError(extension)
  if (!privacyPolicyError) {
    checks.push("✓ Privacy policy uses the canonical GitHub URL.")
  } else {
    const error = `${extension.slug}: ${privacyPolicyError}`
    if (!errors.includes(error)) errors.push(error)
    checks.push("✗ Privacy policy URL is not canonical.")
  }

  if (online) {
    try {
      const response = await fetchImpl(extension.store.privacyPolicyUrl, {
        method: "GET",
        redirect: "follow"
      })
      if (response.ok) {
        checks.push(
          `✓ Privacy policy is publicly reachable (${response.status}).`
        )
      } else {
        errors.push(
          `${extension.slug}: privacy policy returned HTTP ${response.status}`
        )
        checks.push(
          `✗ Privacy policy returned HTTP ${response.status}: ${extension.store.privacyPolicyUrl}`
        )
      }
    } catch (error) {
      errors.push(
        `${extension.slug}: could not reach privacy policy: ${
          error instanceof Error ? error.message : error
        }`
      )
      checks.push("✗ Privacy policy could not be reached.")
    }
  } else {
    checks.push("• Online privacy-policy check skipped.")
  }

  const mode = extension.store.storeId
    ? `Existing item update. Dashboard: ${chromeStoreDashboardUrl(extension)}`
    : `First submission. Create the item at ${chromeStoreDashboardUrl(
        extension
      )}, then run pnpm extension store-id ${extension.slug} <store-id>.`
  const followUp = extension.store.automaticPublish
    ? "After submission, verify the item reaches Published status; approval will publish it automatically."
    : "After approval, return to the dashboard and publish the staged item within 30 days."

  return {
    checks,
    errors,
    report: `${extension.displayName} ${packageJson.version} — Chrome Web Store preflight

${checks.join("\n")}

Submission
${mode}

Follow-up
${followUp}`
  }
}

export function getPrivacyPolicyError(extension) {
  const expected = expectedPrivacyPolicyUrl(extension.slug)
  if (extension.store.privacyPolicyUrl === expected) return undefined
  return `store.privacyPolicyUrl must be ${expected}`
}

function dataUsageLabel(value) {
  return DATA_USAGE_LABELS[value] ?? value
}

function renderPermission(name, justification) {
  return `#### ${name}\n\n${textBlock(justification)}`
}

function textBlock(value) {
  return `\`\`\`text\n${value}\n\`\`\``
}

function titleCase(value) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function sameValues(left, right) {
  const sortedLeft = [...left].sort()
  const sortedRight = [...right].sort()

  return (
    sortedLeft.length === sortedRight.length &&
    sortedLeft.every((value, index) => value === sortedRight[index])
  )
}

async function exists(file) {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

async function readZipManifest(zipPath) {
  const { stdout } = await execFileAsync("unzip", [
    "-p",
    zipPath,
    "manifest.json"
  ])
  return JSON.parse(stdout)
}
